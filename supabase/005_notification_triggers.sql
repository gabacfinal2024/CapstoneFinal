-- Notifications that reach the OTHER person. Run once in the Supabase SQL editor.
--
-- Why this is needed: the notifications table only lets a user write rows for themselves (RLS), so the
-- app could never notify a buyer about a new batch or the other side of a chat about a new message.
-- These SECURITY DEFINER triggers do it on the database side, for every client.

-- 1) A new batch goes on the marketplace -> every rescue buyer is notified
create or replace function public.notify_new_listing() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  p record;
  vendor text;
  note text;
begin
  if new.listing_status <> 'ACTIVE' then return new; end if;
  if tg_op = 'UPDATE' and old.listing_status = 'ACTIVE' then return new; end if;   -- only the moment it becomes active

  select crop_type, quantity_kg, current_price_per_kg into p from products where id = new.product_id;
  select coalesce(nullif(full_name, ''), 'A stall operator') into vendor from profiles where id = new.operator_id;

  note := initcap(lower(coalesce(p.crop_type, 'Produce'))) || ' · ' || coalesce(p.quantity_kg::text, '?') || ' kg · '
          || '₱' || to_char(coalesce(p.current_price_per_kg, 0), 'FM999990.00') || '/kg'
          || case when coalesce(new.discount_percent, 0) > 0 then ' (' || round(new.discount_percent)::text || '% off)' else '' end
          || ' from ' || vendor;

  insert into notifications (user_id, product_id, notification_type, title, message)
  select id, new.product_id, 'MARKETPLACE', 'New batch listed', note
  from profiles
  where role = 'RESCUE_BUYER' and id <> new.operator_id;
  return new;
end $$;

drop trigger if exists trg_notify_new_listing on public.marketplace_listings;
create trigger trg_notify_new_listing after insert or update of listing_status on public.marketplace_listings
  for each row execute function public.notify_new_listing();

-- 2) A chat message -> the other person in the chat is notified
-- The recipient is selected per message, so both buyers and stall operators are notified as the
-- conversation alternates. The trigger runs under the database owner because notification RLS
-- correctly prevents either participant from writing notifications for the other.
-- IoT high-temperature notifications are generated by the Django sensor-reading handler and include
-- its live-device id, which is intentionally not a foreign key to Supabase's separate iot_nodes table.
alter table public.notifications
  add column if not exists device_id bigint;

alter table public.notifications
  add column if not exists thread_id bigint references public.chat_threads(id) on delete cascade;

-- Persist buyer bookmarks so price-drop notifications can be sent only to people following a listing.
create table if not exists public.saved_listings (
  listing_id bigint not null references public.marketplace_listings(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  saved_at timestamptz not null default now(),
  primary key (listing_id, user_id)
);

alter table public.saved_listings enable row level security;
drop policy if exists saved_listings_own on public.saved_listings;
create policy saved_listings_own on public.saved_listings
  for all using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

-- A genuine reduction to an active listing alerts only rescue buyers who saved that listing.
create or replace function public.notify_saved_buyers_price_drop() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  p record;
  message_text text;
begin
  if new.listing_status <> 'ACTIVE'
     or old.listing_status <> 'ACTIVE'
     or new.listed_price >= old.listed_price then
    return new;
  end if;

  select crop_type, quantity_kg into p
    from public.products
    where id = new.product_id;

  message_text := initcap(lower(coalesce(p.crop_type, 'Produce')))
    || case when p.quantity_kg is not null then ' · ' || p.quantity_kg::text || ' kg' else '' end
    || ' price dropped from ₱'
    || to_char(old.listed_price, 'FM999999990.00')
    || ' to ₱'
    || to_char(new.listed_price, 'FM999999990.00')
    || ' for this batch'
    || case when p.quantity_kg > 0 then ' (₱'
         || to_char(new.listed_price / p.quantity_kg, 'FM999999990.00') || '/kg now)' else '' end;

  insert into public.notifications (user_id, product_id, notification_type, title, message)
  select saved.user_id, new.product_id, 'PRICE_DROP',
         'Price dropped on ' || initcap(lower(coalesce(p.crop_type, 'produce'))),
         message_text
    from public.saved_listings saved
    join public.profiles buyer on buyer.id = saved.user_id
   where saved.listing_id = new.id
     and buyer.role = 'RESCUE_BUYER'
     and buyer.id <> new.operator_id;

  return new;
end $$;

drop trigger if exists trg_notify_saved_buyers_price_drop on public.marketplace_listings;
create trigger trg_notify_saved_buyers_price_drop
  after update of listed_price on public.marketplace_listings
  for each row execute function public.notify_saved_buyers_price_drop();

create or replace function public.notify_new_message() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  t record;
  listing record;
  recipient uuid;
  sender text;
  context text;
begin
  select operator_id, buyer_id into t from chat_threads where id = new.thread_id;
  if not found then return new; end if;
  if new.sender_id <> t.operator_id and new.sender_id <> t.buyer_id then return new; end if;
  recipient := case when new.sender_id = t.operator_id then t.buyer_id else t.operator_id end;
  if recipient is null or recipient = new.sender_id then return new; end if;
  select coalesce(nullif(full_name, ''), 'Someone') into sender from profiles where id = new.sender_id;
  select l.product_id, p.crop_type, p.quantity_kg, l.listed_price
    into listing
    from chat_threads ct
    join marketplace_listings l on l.id = ct.listing_id
    join products p on p.id = l.product_id
    where ct.id = new.thread_id;
  context := initcap(lower(coalesce(listing.crop_type, 'Produce'))) || ' · '
    || coalesce(listing.quantity_kg::text, '?') || ' kg · ₱'
    || to_char(coalesce(listing.listed_price, 0), 'FM999990.00') || '/kg';
  insert into notifications (user_id, product_id, thread_id, notification_type, title, message)
  values (
    recipient,
    listing.product_id,
    new.thread_id,
    'NEW_MESSAGE',
    'New message from ' || sender,
    left(context || ' — ' || new.message_text, 500)
  );
  return new;
end $$;

drop trigger if exists trg_notify_new_message on public.chat_messages;
create trigger trg_notify_new_message after insert on public.chat_messages
  for each row execute function public.notify_new_message();

-- 3) Realtime: let the apps hear about new notifications / messages / listings the moment they happen
do $$
declare t text;
begin
  foreach t in array array['notifications', 'chat_messages', 'marketplace_listings'] loop
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;
